import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  buildGrammar,
  parseAssignments,
  placeKanji,
  packUidMap,
  regroup,
  type GrammarSpec,
  type LessonFile,
  type Row,
} from './lib/n5Restructure';

/**
 * One-time N3 restructure (2026-11, docs/content/n3-restructure.md): N3 grammar and vocab
 * leave their old lessons (vocab followed Minna no Nihongo Chūkyū I–II) for this app's own 24-lesson sequence.
 *
 *  - grammar: replaced by the authored batches in scripts/batches/n3-grammar/*.json
 *    (every point rewritten; each lists the old uids it replaces);
 *  - vocab: every row moves to the lesson in scripts/batches/n3-vocab-lessons.json, core
 *    words with example sentences first; no row changes otherwise;
 *  - kanji: each follows the vocab to the first lesson whose words use it.
 *
 * Writes the three data files and grammar-app/src/store/n3RestructureUids.ts (old uid →
 * new uid, for the AI-cache migration). Refuses to run on data it has already restructured.
 *
 *   npx tsx scripts/restructure-n3.ts [--dry-run]
 */

const DATA = 'grammar-app/src/data/n3';
const BATCH = 'scripts/batches';
const UID_MODULE = 'grammar-app/src/store/n3RestructureUids.ts';
const DRY = process.argv.includes('--dry-run');
const LESSONS = 24;

const read = <T>(p: string): T => JSON.parse(readFileSync(p, 'utf-8')) as T;
const rowsOf = (file: LessonFile): Row[] => Object.values(file).flat();

const grammarFile = read<LessonFile>(`${DATA}/grammar.json`);
const vocabFile = read<LessonFile>(`${DATA}/vocab.json`);
const kanjiFile = read<LessonFile>(`${DATA}/kanji.json`);

// ---- grammar
const specs: Record<string, GrammarSpec[]> = {};
for (const name of readdirSync(join(BATCH, 'n3-grammar')).filter((f) => f.endsWith('.json')).sort()) {
  Object.assign(specs, read<Record<string, GrammarSpec[]>>(join(BATCH, 'n3-grammar', name)));
}
const oldGrammar = rowsOf(grammarFile).map((r) => r.uid);
const replaced = new Set(Object.values(specs).flat().flatMap((s) => s.replaces));
if (!oldGrammar.every((u) => replaced.has(u))) {
  console.error('n3/grammar.json does not hold the pre-restructure rows (already restructured?). Nothing written.');
  process.exit(1);
}
const grammar = buildGrammar(specs, oldGrammar, 'n3', LESSONS);

// ---- vocab
const batch = read<{ assign: Record<string, string> }>(`${BATCH}/n3-vocab-lessons.json`);
const lessonOf = parseAssignments('n3', 'vocab', batch.assign, LESSONS);
const oldVocab = rowsOf(vocabFile);
const unassigned = oldVocab.filter((r) => !lessonOf.has(r.uid)).map((r) => r.uid);
if (unassigned.length || lessonOf.size !== oldVocab.length) {
  console.error(`vocab rows and assignments differ (${unassigned.length} unassigned, ${lessonOf.size} assigned, ${oldVocab.length} rows). Nothing written.`);
  process.exit(1);
}
const vocab = regroup(oldVocab, (r) => lessonOf.get(r.uid)!, 'n3-vocab', (r) => Boolean(r.exampleJp), LESSONS);

// ---- kanji
const oldKanji = rowsOf(kanjiFile);
const cap = Math.ceil(oldKanji.length / LESSONS) + 3;
const kanjiLesson = placeKanji(oldKanji, vocab.file, cap, LESSONS);
const kanji = regroup(oldKanji, (r) => kanjiLesson.get(r.uid)!, 'n3-kanji', () => false, LESSONS);

// ---- report
const counts = (f: LessonFile) => Object.values(f).map((rows) => rows.length).join(' ');
console.log(`grammar: ${oldGrammar.length} → ${rowsOf(grammar.file).length} rows; per lesson ${counts(grammar.file)}`);
console.log(`vocab:   ${oldVocab.length} rows; per lesson ${counts(vocab.file)}`);
console.log(`kanji:   ${oldKanji.length} rows; per lesson ${counts(kanji.file)}`);
if (DRY) process.exit(0);

const json = (f: LessonFile) => `${JSON.stringify(f, null, 2)}\n`;
writeFileSync(`${DATA}/grammar.json`, json(grammar.file));
writeFileSync(`${DATA}/vocab.json`, json(vocab.file));
writeFileSync(`${DATA}/kanji.json`, json(kanji.file));
writeFileSync(
  UID_MODULE,
  `// Generated by scripts/restructure-n3.ts — do not edit.
// Old N3 uid → new uid after the 2026-11 restructure, as "old>new" pairs without the
// "n3-<section>-" prefix (unchanged uids omitted). Read by store/aiCacheMigration.ts (v13).

export const N3_GRAMMAR_UIDS = '${packUidMap(grammar.map, 'n3-grammar-')}';

export const N3_VOCAB_UIDS = '${packUidMap(vocab.map, 'n3-vocab-')}';

export const N3_KANJI_UIDS = '${packUidMap(kanji.map, 'n3-kanji-')}';
`
);
console.log(`wrote ${DATA}/{grammar,vocab,kanji}.json and ${UID_MODULE}`);
