/** The titles a hit stands for: its own, plus the removed dictionary form it now covers. */
export function titleAliases(title: string): string[] {
  const dict = Object.entries(DEDUPED_TO_MASU).find(([, masu]) => masu === title)?.[0];
  return dict ? [title, dict] : [title];
}
