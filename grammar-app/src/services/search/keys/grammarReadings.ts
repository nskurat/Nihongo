const BY_LENGTH = [...GRAMMAR_READINGS].sort((a, b) => b[0].length - a[0].length);

/** A title with every kanji run that has a curated reading spelled in kana (one string per reading choice). */
export function kanaVariants(title: string): string[] {
  let variants = [title];
  for (const [written, reading] of BY_LENGTH) {
    if (!variants[0].includes(written)) continue;
    const readings = typeof reading === 'string' ? [reading] : reading;
    variants = variants.flatMap((v) => readings.map((r) => v.split(written).join(r)));
  }
  return variants.filter((v) => v !== title);
}
