export function liveCountMessage(totals: Record<DocType, number>, order: readonly DocType[]): string {
  const total = order.reduce((n, t) => n + (totals[t] ?? 0), 0);
  const parts = order.filter((t) => totals[t] > 0).map((t) => `${totals[t]} ${S.typeLabelLower[t]}`);
  return `${total} result${total === 1 ? '' : 's'}${parts.length ? `: ${parts.join(', ')}` : ''}.`;
}
